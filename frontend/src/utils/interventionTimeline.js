// The client-level intervention timeline: one chronological, date-deduped feed built from
// the events the workspace already records on each target — phase history entries, phase
// lines, phase ranges and graph notes. Nothing new is collected and nothing is written back;
// the merge is a read-only presentation layer over `programs`, `phaseLines`, `phaseRanges`
// and `graphNotes` exactly as they exist today.
//
// Merge rules (ANALYTICS_LANDING_FINDINGS.md §8.1 item 6):
//   · a phase change and its automated companion phase line on the same target and date
//     collapse into one event (the automated line becomes a note on the phase event);
//   · manual phase lines, phase ranges and graph notes stay distinct events;
//   · identical events (same kind, target, date and label) are de-duplicated.
import { isInScopeWindow, scopePrograms } from './analyticsScope.js';
import { targetMilestones } from './targetAnalytics.js';
import { PHASE_LABELS } from './targetHealth.js';

export const TIMELINE_LIMIT = 25;

export const TIMELINE_KINDS = {
  phase: { id: 'phase', label: 'Phase change', group: 'phases', weight: 0 },
  line: { id: 'line', label: 'Phase line', group: 'context', weight: 1 },
  range: { id: 'range', label: 'Phase range', group: 'context', weight: 2 },
  note: { id: 'note', label: 'Graph note', group: 'context', weight: 3 }
};

export const TIMELINE_FILTERS = [
  { id: 'all', label: 'All events', match: () => true },
  { id: 'phases', label: 'Phase changes', match: event => event.kind === 'phase' },
  { id: 'context', label: 'Notes & ranges', match: event => event.kind !== 'phase' }
];

const MASTERED_PHASES = ['Maintenance', 'Generalization', 'Completed'];
const PAUSED_PHASES = ['OnHold', 'Discontinued'];
const MONTH_NAMES = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

// Wording a phase line uses when it is simply narrating the phase change it sits on. A line
// with one of these labels on the same target and date as a phase change is that change's
// companion, whether it was generated by the workspace or typed by a clinician.
const PHASE_COMPANION_LABELS = {
  Baseline: ['baseline'],
  Acquisition: ['teaching begins', 'teaching introduced', 'teaching'],
  Maintenance: ['mastery criterion met', 'moved to maintenance', 'maintenance'],
  Generalization: ['generalization probes', 'generalization across settings', 'community generalization', 'group setting generalization', 'generalization'],
  Completed: ['target completed', 'completed'],
  OnHold: ['placed on hold', 'on hold'],
  Discontinued: ['discontinued']
};

export function isPhaseCompanion(label, phase) {
  const text = String(label || '').trim().toLowerCase();
  if (!text) return false;
  return (PHASE_COMPANION_LABELS[phase] || []).some(candidate => text === candidate || text.startsWith(candidate));
}

function phaseTone(phase) {
  if (MASTERED_PHASES.includes(phase)) return 'positive';
  if (PAUSED_PHASES.includes(phase)) return 'attention';
  return 'neutral';
}

// A phase line's wording already carries its meaning; the tone follows the wording, never a
// raw color. Unknown labels stay neutral.
function lineTone(label) {
  const text = String(label || '').toLowerCase();
  if (/(discontinu|on hold|hold|flat trend|pause)/.test(text)) return 'attention';
  if (/(master|complet|generaliz|maintenance)/.test(text)) return 'positive';
  return 'neutral';
}

function targetRecord(program, target) {
  return {
    targetId: target.id, targetName: target.name,
    programId: program.id, programName: program.name, category: program.category
  };
}

function phaseEvent(program, target, milestone) {
  return {
    key: `phase|${target.id}|${milestone.date}|${milestone.phase}`,
    kind: 'phase',
    date: milestone.date,
    ...targetRecord(program, target),
    phase: milestone.phase,
    phaseLabel: PHASE_LABELS[milestone.phase] || milestone.phase,
    title: milestone.label,
    detail: '',
    tone: phaseTone(milestone.phase),
    source: 'Phase history',
    automated: false,
    companions: []
  };
}

function lineEvent(program, target, line) {
  return {
    key: `line|${target.id}|${line.date}|${String(line.label || '').trim()}|${line.isAutomated ? 'auto' : 'manual'}`,
    kind: 'line',
    date: line.date,
    ...targetRecord(program, target),
    title: line.label || 'Phase line',
    detail: line.staffName ? `${line.staffName}` : '',
    tone: lineTone(line.label),
    source: line.source || (line.isAutomated ? 'Automated' : 'Manual'),
    automated: Boolean(line.isAutomated),
    companions: [],
    recordId: line.id
  };
}

function rangeEvent(program, target, range) {
  return {
    key: `range|${range.id || `${target.id}|${range.startDate}|${range.endDate}|${String(range.label || '').trim()}`}`,
    kind: 'range',
    date: range.startDate,
    endDate: range.endDate,
    ...targetRecord(program, target),
    title: range.label || 'Phase range',
    detail: `${range.startDate} – ${range.endDate}`,
    tone: 'neutral',
    source: 'Phase range',
    automated: false,
    companions: [],
    recordId: range.id
  };
}

function noteEvent(program, target, note) {
  return {
    key: `note|${note.id || `${target.id}|${note.date}|${String(note.noteText || '').trim()}`}`,
    kind: 'note',
    date: note.date,
    ...targetRecord(program, target),
    title: note.noteText || 'Graph note',
    detail: note.staffName || '',
    tone: 'neutral',
    source: 'Graph note',
    automated: false,
    companions: [],
    recordId: note.id
  };
}

// Collapse a phase line into the phase change it annotates. Automated lines are the primary
// case; a manual line that repeats the very transition recorded on the target that day (for
// example a clinician typing "Target completed" on a completion date) is the same pair, so it
// collapses too. Every other line — an intervention change, a schedule note — stays a distinct
// event, as do all phase ranges and graph notes.
export function collapsePhaseLines(events = []) {
  // Work on shallow copies so the caller's event objects are never mutated.
  const copies = new Map();
  const phasesByTargetDate = new Map();
  for (const event of events) {
    if (event.kind !== 'phase') continue;
    const copy = { ...event, companions: [...(event.companions || [])] };
    copies.set(event, copy);
    const key = `${event.targetId}|${event.date}`;
    if (!phasesByTargetDate.has(key)) phasesByTargetDate.set(key, []);
    phasesByTargetDate.get(key).push(copy);
  }
  const kept = [];
  let collapsed = 0;
  for (const event of events) {
    if (event.kind === 'line') {
      const hosts = phasesByTargetDate.get(`${event.targetId}|${event.date}`) || [];
      // Prefer a mastery-phase event when a target has several changes on one date.
      const host = hosts.find(candidate => MASTERED_PHASES.includes(candidate.phase)) || hosts[0];
      if (host && (event.automated || isPhaseCompanion(event.title, host.phase))) {
        if (!host.companions.some(companion => companion.label === event.title)) {
          host.companions.push({
            id: event.recordId || event.key, label: event.title, source: event.source, automated: event.automated
          });
        }
        collapsed += 1;
        continue;
      }
    }
    kept.push(copies.get(event) || event);
  }
  return { events: kept, collapsed };
}

// Date-dedupe: one row per event identity, keeping the first occurrence (events are built
// chronologically per source) and merging any absorbed companions.
export function dedupeTimeline(events = []) {
  const seen = new Map();
  for (const event of events) {
    const existing = seen.get(event.key);
    if (!existing) {
      seen.set(event.key, { ...event, companions: [...(event.companions || [])] });
      continue;
    }
    const merged = [...existing.companions];
    for (const companion of event.companions || []) {
      if (!merged.some(item => item.label === companion.label)) merged.push(companion);
    }
    seen.set(event.key, { ...existing, companions: merged, detail: existing.detail || event.detail || '' });
  }
  return [...seen.values()];
}

export function sortTimelineEvents(events = []) {
  const weight = event => TIMELINE_KINDS[event.kind]?.weight ?? Object.keys(TIMELINE_KINDS).length;
  return [...events].sort((a, b) =>
    String(b.date).localeCompare(String(a.date))
    || weight(a) - weight(b)
    || a.targetName.localeCompare(b.targetName)
    || String(a.title).localeCompare(String(b.title))
  );
}

function overlapsWindow(event, { asOfDate = null, windowStart = null } = {}) {
  if (event.kind === 'range') {
    const end = event.endDate || event.date;
    if (windowStart && end < String(windowStart).slice(0, 10)) return false;
    if (asOfDate && event.date > String(asOfDate).slice(0, 10)) return false;
    return true;
  }
  return isInScopeWindow(event.date, { asOfDate, start: windowStart });
}

export function filterTimelineEvents(events = [], filterId = 'all') {
  const filter = TIMELINE_FILTERS.find(entry => entry.id === filterId);
  return filter ? events.filter(filter.match) : [...events];
}

export function timelineCounts(events = []) {
  const counts = { phase: 0, line: 0, range: 0, note: 0 };
  for (const event of events) counts[event.kind] += 1;
  return counts;
}

// Build the merged feed. `programs` may be the client's programs (already client-scoped);
// `programScope` is applied defensively so the component cannot show out-of-scope targets.
export function buildInterventionTimeline({
  programs = [], phaseLines = [], phaseRanges = [], graphNotes = [],
  asOfDate = null, windowStart = null, programScope = 'all', limit = null
} = {}) {
  const index = new Map();
  for (const program of scopePrograms(programs, programScope)) {
    for (const target of program.targets || []) index.set(target.id, { program, target });
  }

  const built = [];
  for (const { program, target } of index.values()) {
    for (const milestone of targetMilestones(target)) {
      if (!milestone.date) continue;
      built.push(phaseEvent(program, target, milestone));
    }
  }
  for (const line of phaseLines) {
    const entry = index.get(line.targetId);
    if (entry && line.date) built.push(lineEvent(entry.program, entry.target, line));
  }
  for (const range of phaseRanges) {
    const entry = index.get(range.targetId);
    if (entry && range.startDate) built.push(rangeEvent(entry.program, entry.target, range));
  }
  for (const note of graphNotes) {
    const entry = index.get(note.targetId);
    if (entry && note.date) built.push(noteEvent(entry.program, entry.target, note));
  }

  const { events: merged, collapsed } = collapsePhaseLines(built);
  const unique = dedupeTimeline(merged);
  const inWindow = unique.filter(event => overlapsWindow(event, { asOfDate, windowStart }));
  const events = sortTimelineEvents(inWindow);
  const visible = limit ? events.slice(0, limit) : events;
  return {
    events: visible,
    total: events.length,
    counts: timelineCounts(events),
    collapsed,
    firstDate: events.at(-1)?.date || null,
    lastDate: events[0]?.date || null
  };
}

export function timelineMonthLabel(date) {
  if (!date) return '';
  const parsed = new Date(`${String(date).slice(0, 10)}T12:00:00Z`);
  if (Number.isNaN(parsed.getTime())) return String(date);
  return `${MONTH_NAMES[parsed.getUTCMonth()]} ${parsed.getUTCFullYear()}`;
}

// Month groups keep the feed scannable without inventing a second sort order.
export function groupTimelineByMonth(events = []) {
  const groups = [];
  let current = null;
  for (const event of events) {
    const id = String(event.date).slice(0, 7);
    if (!current || current.id !== id) {
      current = { id, label: timelineMonthLabel(event.date), events: [] };
      groups.push(current);
    }
    current.events.push(event);
  }
  return groups;
}

// Plain-language row description used as the accessible name of the drilldown button.
export function describeTimelineEvent(event) {
  const kind = TIMELINE_KINDS[event.kind]?.label || 'Event';
  const span = event.kind === 'range' && event.endDate ? ` through ${event.endDate}` : '';
  const subject = event.kind === 'phase'
    ? `${event.targetName} moved to ${event.phaseLabel}`
    : event.targetName;
  return `${event.date}. ${kind}: ${event.title}${span}. ${subject}, ${event.programName}. Open in target analysis.`;
}
