#!/usr/bin/env node
// Builds the in-app documentation module from the two source documents.
//
// The wiki (docs/wiki/Home.md) is the source of truth for the platform guide and
// the tech-stack document for the reference section. This script parses both and
// emits frontend/src/data/docs/wikiPages.js, which is the generated mirror the
// documentation screen reads.
//
// Run it after editing either source:  npm run docs:build
// Check it in CI:                             npm run docs:check

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..');

const WIKI_PATH = join(repoRoot, 'docs', 'wiki', 'Home.md');
const TECH_PATH = join(repoRoot, 'TECH_STACK.md');
const OUTPUT_PATH = join(repoRoot, 'frontend', 'src', 'data', 'docs', 'wikiPages.js');

// The documentation viewer's heading slugs: dots are removed so "6.3 Visual
// analysis" becomes "63-visual-analysis", matching the wiki's own link style.
function slugify(text) {
  return String(text)
    .toLowerCase()
    .replace(/\./g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function readHeadings(markdown) {
  const headings = [];
  const re = /^(#{1,6}) (.+?)\s*$/gm;
  let match;
  while ((match = re.exec(markdown)) !== null) {
    headings.push({ depth: match[1].length, text: match[2].trim() });
  }
  return headings;
}

// The wiki splits into one page per top-level part. Everything before the first
// part becomes the start-here page.
function splitWiki(markdown) {
  const partRe = /^# (Part \d+: .*)$/gm;
  const parts = [];
  let match;
  while ((match = partRe.exec(markdown)) !== null) {
    parts.push({ start: match.index, title: match[1] });
  }
  const bounds = [0, ...parts.map(part => part.start), markdown.length];
  const pages = [{ id: 'start-here', title: 'Start here', order: 0, markdown: markdown.slice(bounds[0], bounds[1]) }];
  parts.forEach((part, index) => {
    pages.push({
      id: slugify(part.title),
      title: part.title.replace(/^Part \d+: /, ''),
      order: index + 1,
      markdown: markdown.slice(bounds[index + 1], bounds[index + 2])
    });
  });
  return pages;
}

function build() {
  // The sources are checked out with CRLF on Windows; the generated module is
  // committed with LF, so line endings are normalized on the way in.
  const wiki = readFileSync(WIKI_PATH, 'utf8').replace(/\r\n/g, '\n');
  const tech = readFileSync(TECH_PATH, 'utf8').replace(/\r\n/g, '\n');
  const wikiPages = splitWiki(wiki);

  // Every page keeps the trailing separator that precedes the next part; only
  // the whitespace after it is trimmed.
  const pageContent = {};
  const owner = {};
  const headingIndex = {};

  wikiPages.forEach(page => {
    pageContent[page.id] = page.markdown.trimEnd();
    readHeadings(page.markdown).forEach(heading => {
      const slug = slugify(heading.text);
      headingIndex[slug] = { depth: heading.depth, text: heading.text };
      owner[slug] = page.id;
    });
  });

  const techHeadingIndex = {};
  readHeadings(tech).forEach(heading => {
    const slug = slugify(heading.text);
    techHeadingIndex[slug] = { depth: heading.depth, text: heading.text };
    owner[slug] = 'tech-stack';
  });

  // The tech-stack document is its own page, whole.
  pageContent['tech-stack'] = tech.trimEnd();

  const docSections = [
    { id: 'wiki', label: 'Platform wiki' },
    { id: 'reference', label: 'Reference' }
  ];

  const docPages = [
    ...wikiPages.map(page => ({ id: page.id, title: page.title, section: 'Wiki', order: page.order })),
    { id: 'tech-stack', title: 'Tech stack & architecture', section: 'Reference', order: 99 }
  ];

  const sections = [
    ['DOC_SECTIONS', docSections],
    ['DOC_PAGES', docPages],
    ['PAGE_CONTENT', pageContent],
    ['PAGE_OWNER', owner],
    ['HEADING_INDEX', headingIndex],
    ['TECH_HEADING_INDEX', techHeadingIndex]
  ];

  const body = sections
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};`)
    .join('\n\n');

  return `// Auto-generated by the documentation build script. Do not edit by hand;
// regenerate from docs/wiki/Home.md and TECH_STACK.md.

${body}

export function pageById(id) {
  return DOC_PAGES.find(page => page.id === id) || null;
}

export function ownerOf(slug) {
  return PAGE_OWNER[slug] ?? null;
}
`;
}

const generated = build();

if (process.argv[2] === '--check') {
  let current = '';
  try {
    current = readFileSync(OUTPUT_PATH, 'utf8');
  } catch {
    console.error(`docs:check failed: ${OUTPUT_PATH} does not exist. Run npm run docs:build.`);
    process.exit(1);
  }
  if (current !== generated) {
    console.error('docs:check failed: the committed documentation module is out of date. Run npm run docs:build.');
    process.exit(1);
  }
  console.log('docs:check passed: the documentation module matches its sources.');
  process.exit(0);
}

writeFileSync(OUTPUT_PATH, generated, 'utf8');
console.log(`docs:build wrote ${OUTPUT_PATH}`);
