import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

const wiki = readFileSync(join(repoRoot, 'docs', 'wiki', 'Home.md'), 'utf8').replace(/\r\n/g, '\n');
const tech = readFileSync(join(repoRoot, 'TECH_STACK.md'), 'utf8').replace(/\r\n/g, '\n');
const generated = readFileSync(join(repoRoot, 'frontend', 'src', 'data', 'docs', 'wikiPages.js'), 'utf8').replace(/\r\n/g, '\n');

const slugify = text =>
  String(text)
    .toLowerCase()
    .replace(/\./g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const wikiParts = [...wiki.matchAll(/^# (Part \d+: .*)$/gm)].map(match => ({
  start: match.index,
  title: match[1]
}));

test('the wiki splits into one page per part, with the opening matter as start-here', () => {
  assert.equal(wikiParts.length, 9, 'the wiki has nine parts');
  assert.ok(wikiParts[0].start > 0, 'there is opening matter before the first part');
});

test('every page in the generated module corresponds to a wiki part', () => {
  // Each part heading becomes a page id, and the opening matter becomes start-here.
  for (const part of wikiParts) {
    const pageId = slugify(part.title);
    assert.ok(
      generated.includes(`"${pageId}"`),
      `the generated module carries a page for ${part.title}`
    );
  }
  assert.ok(generated.includes('"start-here"'));
});

test('the generated page content is the wiki text, split at the part boundaries', () => {
  // The content of each page is the wiki slice for that part, with the trailing
  // whitespace trimmed. A page that drifted from the wiki means the generated
  // module was not rebuilt after an edit.
  const bounds = [0, ...wikiParts.map(part => part.start), wiki.length];
  const pageIds = ['start-here', ...wikiParts.map(part => slugify(part.title))];
  pageIds.forEach((pageId, index) => {
    const slice = wiki.slice(bounds[index], bounds[index + 1]).trimEnd();
    const marker = `"${pageId}": "`;
    const at = generated.indexOf(marker);
    assert.notEqual(at, -1, `${pageId} has content in the generated module`);
    // The content is JSON-escaped in the module; compare on the escaped form.
    const escaped = JSON.stringify(slice).slice(1, -1);
    assert.ok(
      generated.includes(escaped.slice(0, 200)),
      `${pageId} content matches the wiki (checked the first 200 characters)`
    );
  });
});

test('the generated module carries every wiki heading in its heading index', () => {
  const headings = [...wiki.matchAll(/^(#{1,6}) (.+?)\s*$/gm)];
  assert.ok(headings.length > 100, 'the wiki has a full set of headings');
  for (const heading of headings) {
    const slug = slugify(heading[2]);
    assert.ok(
      generated.includes(`"${slug}": {\n    "depth": ${heading[1].length},`),
      `the heading index carries ${heading[2]} at depth ${heading[1].length}`
    );
  }
});

test('every heading slug in the owner map points at the page that contains it', () => {
  // A heading owned by the wrong page breaks the in-app cross-links: clicking a
  // link would open the right heading on the wrong page.
  const bounds = [0, ...wikiParts.map(part => part.start), wiki.length];
  const pageIds = ['start-here', ...wikiParts.map(part => slugify(part.title))];
  pageIds.forEach((pageId, index) => {
    const slice = wiki.slice(bounds[index], bounds[index + 1]);
    for (const heading of slice.matchAll(/^(#{1,6}) (.+?)\s*$/gm)) {
      const slug = slugify(heading[2]);
      assert.ok(
        generated.includes(`"${slug}": "${pageId}"`),
        `${heading[2]} is owned by ${pageId}`
      );
    }
  });
});

test('the tech-stack document is a page of its own', () => {
  assert.ok(generated.includes('"id": "tech-stack"'), 'the tech stack is a listed page');
  assert.ok(generated.includes('"tech-stack": "# Welina Analytics'), 'the tech stack has page content');
  for (const heading of tech.matchAll(/^(#{1,6}) (.+?)\s*$/gm)) {
    const slug = slugify(heading[2]);
    assert.ok(
      generated.includes(`"${slug}": "tech-stack"`),
      `the tech-stack heading ${heading[2]} is owned by the tech stack page`
    );
  }
});

test('the generated module keeps the helpers the documentation screen imports', () => {
  assert.ok(generated.includes('export function pageById(id)'));
  assert.ok(generated.includes('export function ownerOf(slug)'));
  assert.ok(generated.includes('export const DOC_SECTIONS'));
  assert.ok(generated.includes('export const DOC_PAGES'));
  assert.ok(generated.includes('export const PAGE_CONTENT'));
  assert.ok(generated.includes('export const PAGE_OWNER'));
});

test('the generated module declares itself generated, so nobody edits it by hand', () => {
  assert.match(generated, /^﻿?\/\/ Auto-generated by the documentation build script\./);
});
